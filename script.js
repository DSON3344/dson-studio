// Called by the reCAPTCHA API once it finishes loading.
window.onRecaptchaLoad = renderRecaptcha;

function applyTheme(theme) {
  if (theme === 'light') {
    document.documentElement.setAttribute('data-theme', 'light');
  } else {
    document.documentElement.removeAttribute('data-theme');
  }
  try { localStorage.setItem('dson-theme', theme); } catch (e) {}

  const meta = document.getElementById('themeColorMeta');
  if (meta) meta.setAttribute('content', theme === 'light' ? '#F5F7FA' : '#0A0D12');

  updateThemeToggleLabel(currentLang);
  renderRecaptcha();
}

document.addEventListener('DOMContentLoaded', () => {
  // Auto-update copyright year
  const yearEl = document.getElementById('footerYear');
  if (yearEl) yearEl.textContent = new Date().getFullYear();

  applyLang(currentLang);

  const themeToggle = document.getElementById('themeToggle');
  if (themeToggle) {
    updateThemeToggleLabel(currentLang);
    themeToggle.addEventListener('click', () => {
      applyTheme(getCurrentTheme() === 'light' ? 'dark' : 'light');
    });
  }

  const langSwitch = document.getElementById('langSwitch');
  if (langSwitch) {
    langSwitch.addEventListener('click', (e) => {
      const btn = e.target.closest('button');
      const targetLang = btn ? btn.dataset.lang : (currentLang === 'zh' ? 'en' : 'zh');
      if (targetLang === currentLang) return;
      currentLang = targetLang;
      applyLang(currentLang);
    });
  }

  // Mobile nav toggle
  const navToggle = document.getElementById('navToggle');
  const mobileNav = document.getElementById('mobileNav');
  function closeMobileNav() {
    if (!navToggle || !mobileNav) return;
    navToggle.setAttribute('aria-expanded', 'false');
    mobileNav.classList.remove('open');
  }
  if (navToggle && mobileNav) {
    navToggle.addEventListener('click', () => {
      const isOpen = navToggle.getAttribute('aria-expanded') === 'true';
      navToggle.setAttribute('aria-expanded', isOpen ? 'false' : 'true');
      mobileNav.classList.toggle('open', !isOpen);
    });
    mobileNav.querySelectorAll('a').forEach(link => {
      link.addEventListener('click', closeMobileNav);
    });
    document.addEventListener('click', (e) => {
      if (!navToggle.contains(e.target) && !mobileNav.contains(e.target)) closeMobileNav();
    });
    document.addEventListener('keydown', (e) => {
      if (e.key === 'Escape') closeMobileNav();
    });
  }

  // Service category tabs
  const tabButtons = document.querySelectorAll('.tab-btn');
  tabButtons.forEach(btn => {
    btn.addEventListener('click', () => {
      const targetId = btn.getAttribute('data-target');
      tabButtons.forEach(b => {
        b.classList.remove('active');
        b.setAttribute('aria-selected', 'false');
      });
      btn.classList.add('active');
      btn.setAttribute('aria-selected', 'true');
      document.querySelectorAll('.service-panel').forEach(panel => {
        panel.classList.toggle('active', panel.id === targetId);
      });
    });
  });

  // Handle contact form submission via EmailJS
  // Setup required: sign up at emailjs.com, add an email service (e.g. Gmail
  // connected to hello@dson.site), create a template with variables
  // matching the input `name` attributes below ({{name}}, {{email}},
  // {{service}}, {{message}}), then replace the three placeholders here.
  const EMAILJS_PUBLIC_KEY = 'D97dSRtpVsVCq_Kin';
  const EMAILJS_SERVICE_ID = 'service_xy0eix7';
  const EMAILJS_TEMPLATE_ID = 'template_golm6rw';
  if (window.emailjs) {
    emailjs.init({ publicKey: EMAILJS_PUBLIC_KEY });
  }

  const contactForm = document.getElementById('contactForm');
  if (contactForm) {
    contactForm.addEventListener('submit', function (e) {
      e.preventDefault();
      const form = this;

      // Honeypot spam check — if this hidden field got filled, silently drop it
      const honeypot = form.querySelector('input[name="_gotcha"]');
      if (honeypot && honeypot.value) return;

      // reCAPTCHA must be solved before sending; the token rides along with
      // sendForm automatically as the g-recaptcha-response field.
      const captchaMsg = form.querySelector('.form-error--captcha');
      if (captchaMsg) captchaMsg.style.display = 'none';
      if (recaptchaWidgetId !== null && window.grecaptcha) {
        if (!grecaptcha.getResponse(recaptchaWidgetId)) {
          if (captchaMsg) captchaMsg.style.display = 'block';
          return;
        }
      }

      const successMsg = form.querySelector('.submitted');
      const errorMsg = form.querySelector('.form-error');
      const submitBtn = form.querySelector('button[type="submit"]');
      const btnLabel = submitBtn ? submitBtn.querySelector('.btn-label') : null;

      if (successMsg) successMsg.style.display = 'none';
      if (errorMsg) errorMsg.style.display = 'none';
      if (submitBtn) submitBtn.disabled = true;
      const originalLabel = btnLabel ? btnLabel.textContent : null;
      if (btnLabel) btnLabel.textContent = currentLang === 'zh' ? '发送中…' : 'Sending…';

      emailjs.sendForm(EMAILJS_SERVICE_ID, EMAILJS_TEMPLATE_ID, form)
        .then(() => {
          form.reset();
          if (successMsg) successMsg.style.display = 'block';
        })
        .catch(() => {
          if (errorMsg) errorMsg.style.display = 'block';
        })
        .finally(() => {
          if (recaptchaWidgetId !== null && window.grecaptcha) grecaptcha.reset(recaptchaWidgetId);
          if (submitBtn) submitBtn.disabled = false;
          if (btnLabel && originalLabel) btnLabel.textContent = originalLabel;
        });
    });
  }

  // Scroll progress bar
  const progressBar = document.getElementById('scrollProgress');
  const backToTop = document.getElementById('backToTop');
  function onScroll() {
    const scrollTop = window.scrollY;
    const docHeight = document.documentElement.scrollHeight - window.innerHeight;
    const pct = docHeight > 0 ? (scrollTop / docHeight) * 100 : 0;
    if (progressBar) progressBar.style.width = pct + '%';
    if (backToTop) backToTop.classList.toggle('visible', scrollTop > 600);
  }
  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();

  if (backToTop) {
    backToTop.addEventListener('click', () => {
      window.scrollTo({ top: 0, behavior: 'smooth' });
    });
  }

  // Active nav link highlighting
  const navLinks = document.querySelectorAll('.navlinks a[href^="#"], .mobile-nav a[href^="#"]');
  const sections = Array.from(new Set(Array.from(navLinks).map(link => link.getAttribute('href'))))
    .map(href => document.querySelector(href))
    .filter(Boolean);

  if ('IntersectionObserver' in window && sections.length) {
    const navObserver = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          navLinks.forEach(link => link.classList.remove('active'));
          document.querySelectorAll(`.navlinks a[href="#${entry.target.id}"], .mobile-nav a[href="#${entry.target.id}"]`)
            .forEach(link => link.classList.add('active'));
        }
      });
    }, { rootMargin: '-40% 0px -50% 0px', threshold: 0 });
    sections.forEach(sec => navObserver.observe(sec));
  }

  // Scroll reveal animation
  const revealTargets = document.querySelectorAll(
    '.section-head, .glass-card, .process-step, .case-card, .cta-strip, .faq-item, .trust-bar'
  );
  revealTargets.forEach(el => el.classList.add('reveal'));

  if ('IntersectionObserver' in window) {
    const revealObserver = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add('in-view');
          revealObserver.unobserve(entry.target);
        }
      });
    }, { threshold: 0.15 });
    revealTargets.forEach(el => revealObserver.observe(el));
  } else {
    revealTargets.forEach(el => el.classList.add('in-view'));
  }

  // Scale embedded website previews so they always render desktop layout
  function scaleBrowserFrames() {
    document.querySelectorAll('.browser-frame-wrap').forEach(wrap => {
      const iframe = wrap.querySelector('.browser-frame');
      if (!iframe) return;
      const wrapWidth = wrap.clientWidth;
      const nativeWidth = 1440;
      const scale = wrapWidth / nativeWidth;
      iframe.style.transform = `scale(${scale})`;
    });
  }
  scaleBrowserFrames();
  window.addEventListener('resize', scaleBrowserFrames);

  // Case study modal
  const caseModalOverlay = document.getElementById('caseModalOverlay');
  const caseModalClose = document.getElementById('caseModalClose');
  const openVisionLogicBtn = document.getElementById('openVisionLogicCase');

  function openCaseModal() {
    caseModalOverlay.classList.add('active');
    document.body.style.overflow = 'hidden';
  }
  function closeCaseModal() {
    caseModalOverlay.classList.remove('active');
    document.body.style.overflow = '';
  }
  if (openVisionLogicBtn) openVisionLogicBtn.addEventListener('click', openCaseModal);
  if (caseModalClose) caseModalClose.addEventListener('click', closeCaseModal);
  if (caseModalOverlay) {
    caseModalOverlay.addEventListener('click', (e) => {
      if (e.target === caseModalOverlay) closeCaseModal();
    });
  }
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && caseModalOverlay && caseModalOverlay.classList.contains('active')) {
      closeCaseModal();
    }
  });
});